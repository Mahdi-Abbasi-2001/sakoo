// Reads ../docs/openapi.json and ../docs/events.d.ts and writes src/api/schema.gen.ts and src/api/events.ts.
// The OpenAPI file only describes request bodies, so response types live in src/api/types.ts (written from docs/api.md).
import fs from 'node:fs';
import path from 'node:path';
const ROOT = path.resolve(import.meta.dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(ROOT, '../docs/openapi.json'), 'utf8'));
const ref = (s) => s.replace('#/components/schemas/', '');
function ts(s, ind = '') {
  if (!s) return 'unknown';
  if (s.$ref) return ref(s.$ref);
  if (s.anyOf) return s.anyOf.map((x) => ts(x, ind)).join(' | ');
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  switch (s.type) {
    case 'string': return s.contentMediaType ? 'File | Blob' : 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${ts(s.items, ind)}[]`;
    case 'object': {
      if (!s.properties) return 'Record<string, unknown>';
      const req = new Set(s.required || []);
      return '{\n' + Object.entries(s.properties).map(([k, v]) => `${ind}  ${k}${req.has(k) ? '' : '?'}: ${ts(v, ind + '  ')};`).join('\n') + `\n${ind}}`;
    }
    default: return 'unknown';
  }
}
let out = '// generated by scripts/gen-api.mjs from docs/openapi.json: do not edit\n\n';
for (const [name, s] of Object.entries(spec.components.schemas)) out += `export interface ${name} ${ts(s)}\n\n`;
out += 'export const ROUTES = {\n';
for (const [p, v] of Object.entries(spec.paths)) for (const [m, o] of Object.entries(v)) {
  const id = o.operationId || `${m}_${p}`;
  const body = o.requestBody?.content ? Object.keys(o.requestBody.content)[0] : null;
  out += `  ${JSON.stringify(id)}: { method: ${JSON.stringify(m.toUpperCase())}, path: ${JSON.stringify(p)}, body: ${JSON.stringify(body)} },\n`;
}
out += '} as const;\n';
fs.mkdirSync(path.join(ROOT, 'src/api'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/api/schema.gen.ts'), out);
fs.writeFileSync(path.join(ROOT, 'src/api/events.ts'), '// generated by scripts/gen-api.mjs: a verbatim copy of docs/events.d.ts\n' + fs.readFileSync(path.join(ROOT, '../docs/events.d.ts'), 'utf8'));
console.log('api types written');
