// Copies the self-hosted font files out of node_modules and writes src/styles/fonts.css, including
// fallback faces whose metrics are adjusted to the real fonts so the swap does not move anything.
import fs from 'node:fs';
import path from 'node:path';
import * as fontkit from 'fontkit';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'src/assets/fonts');
fs.mkdirSync(OUT, { recursive: true });
const nm = (p) => path.join(ROOT, 'node_modules', p);

const FILES = [
  { fam: 'Sora', src: '@fontsource-variable/sora/files/sora-latin-wght-normal.woff2', out: 'sora-latin.woff2', range: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD', w: '100 800' },
  { fam: 'Vazirmatn', src: '@fontsource-variable/vazirmatn/files/vazirmatn-arabic-wght-normal.woff2', out: 'vazirmatn-arabic.woff2', range: 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC', w: '100 900' },
  { fam: 'Vazirmatn', src: '@fontsource-variable/vazirmatn/files/vazirmatn-latin-wght-normal.woff2', out: 'vazirmatn-latin.woff2', range: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD', w: '100 900' },
  { fam: 'JetBrains Mono', src: '@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2', out: 'jetbrains-mono-latin.woff2', range: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD', w: '100 800' },
];
for (const f of FILES) fs.copyFileSync(nm(f.src), path.join(OUT, f.out));

// English letter frequencies (a-z) for a weighted average advance, the same idea capsize uses.
const FREQ = { a: 8.17, b: 1.49, c: 2.78, d: 4.25, e: 12.7, f: 2.23, g: 2.02, h: 6.09, i: 6.97, j: 0.15, k: 0.77, l: 4.03, m: 2.41, n: 6.75, o: 7.51, p: 1.93, q: 0.1, r: 5.99, s: 6.33, t: 9.06, u: 2.76, v: 0.98, w: 2.36, x: 0.15, y: 1.97, z: 0.07, ' ': 15 };
function metrics(file) {
  const f = fontkit.openSync(path.join(OUT, file));
  const upm = f.unitsPerEm; let sum = 0, tot = 0;
  for (const [ch, w] of Object.entries(FREQ)) { const g = f.layout(ch).glyphs[0]; sum += g.advanceWidth * w; tot += w; }
  return { upm, asc: f.hhea.ascent, desc: f.hhea.descent, gap: f.hhea.lineGap, avg: sum / tot / upm };
}
// Reference metrics of the system fonts we fall back to (Arial = Liberation Sans = Arimo, Courier New = Liberation Mono = Cousine).
const ARIAL = { upm: 2048, asc: 1854, desc: -434, gap: 67, avg: 904 / 2048 };
const COURIER = { upm: 2048, asc: 1705, desc: -615, gap: 0, avg: 1229 / 2048 };
const REG = ['Arial', 'Liberation Sans', 'Arimo', 'Helvetica Neue', 'Helvetica'], BOLD = ['Arial Bold', 'Arial-BoldMT', 'Liberation Sans Bold', 'Arimo Bold', 'Helvetica Neue Bold', 'Helvetica Bold'];
const MREG = ['Courier New', 'Liberation Mono', 'Cousine', 'Courier'], MBOLD = ['Courier New Bold', 'Liberation Mono Bold', 'Cousine Bold', 'Courier Bold'];
// Per-weight widths measured in a real browser (scripts/measure-fonts.mjs), when available: a heavy headline is wider than body text,
// so one scale factor would make the fallback wrap differently from the real font.
const measured = fs.existsSync(path.join(OUT, 'metrics.json')) ? JSON.parse(fs.readFileSync(path.join(OUT, 'metrics.json'), 'utf8')) : null;
function fallback(name, fam, m, ref, locals, boldLocals) {
  const bands = [['100 500', '400', locals], ['600 700', '600', boldLocals], ['800 900', '800', boldLocals]];
  return bands.map(([range, key, src]) => {
    const sa = measured?.[fam]?.[key] ?? m.avg / ref.avg;
    const pct = (v) => ((v / m.upm) / sa * 100).toFixed(2) + '%';
    return `@font-face{font-family:"${name}";font-weight:${range};src:${src.map((l) => `local("${l}")`).join(',')};size-adjust:${(sa * 100).toFixed(2)}%;ascent-override:${pct(m.asc)};descent-override:${pct(Math.abs(m.desc))};line-gap-override:${pct(m.gap)}}`;
  }).join('\n');
}
const mSora = metrics('sora-latin.woff2'), mVaz = metrics('vazirmatn-latin.woff2'), mJb = metrics('jetbrains-mono-latin.woff2');
const face = (f) => `@font-face{font-family:"${f.fam}";font-style:normal;font-weight:${f.w};font-display:swap;src:url("../assets/fonts/${f.out}") format("woff2");unicode-range:${f.range}}`;
const css = `/* generated by scripts/gen-fonts.mjs: do not edit. Self-hosted, subset (Latin and Arabic ranges), font-display: swap. */
${FILES.map(face).join('\n')}
/* fallbacks with adjusted metrics, so the swap to the real fonts does not move anything */
${fallback('Sora Fallback', 'Sora', mSora, ARIAL, REG, BOLD)}
${fallback('Vazirmatn Fallback', 'Vazirmatn', mVaz, ARIAL, REG, BOLD)}
${fallback('JetBrains Mono Fallback', 'JetBrains Mono', mJb, COURIER, MREG, MBOLD)}
:root{--f-sans:"Sora","Sora Fallback",system-ui,sans-serif;--f-fa:"Vazirmatn","Vazirmatn Fallback","Sora Fallback",system-ui,sans-serif;--f-mono:"JetBrains Mono","JetBrains Mono Fallback",ui-monospace,monospace}
`;
fs.writeFileSync(path.join(ROOT, 'src/styles/fonts.css'), css);
console.log('Sora', mSora, '\nVazirmatn', mVaz, '\nJetBrains', mJb);
