// Extracts the blueprint scenes (SVG) from the final landing boards in ../design/landing into src/landing/scenes.gen.ts.
// Every localized word inside a scene is replaced by a {{key}} placeholder that the page fills from the catalogs, so the
// scene text lives in en.json / fa.json like everything else. Geometry differs per language (RTL is mirrored), so both are kept.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const dir = path.resolve(root, '../design/landing');
const WORDS = {
  proposed: ['proposed', 'پیشنهادی'], creating: ['creating', 'در حال ساخت'], live: ['live', 'زنده'],
  unverified: ['price unverified', 'قیمت تأییدنشده'], noport: ['? worker has no port', '? worker پورت ندارد'], answered: ['answered: worker', 'پاسخ: worker'],
  unit_h: [' toman/h', ' تومان/ساعت'], total: ['TOTAL ', 'جمع '], total_hm: [' toman/h · ', ' تومان/ساعت · '], per_mo: ['/mo', '/ماه'],
  notcreated: ['not created', 'ساخته نشده'], netlabel: ['private network · net1', 'شبکه‌ی خصوصی · net1'],
};
const TITLES = {
  replay: ['Replay: the agent reads a project, draws the plan with prices, waits for approval, then creates and verifies the resources', 'بازپخش: عامل پروژه را می‌خواند، طرح را با قیمت می‌کشد، منتظر تأیید می‌ماند و سپس منابع را می‌سازد و بررسی می‌کند'],
  net: ['The private network net1: each resource joins it when it is created', 'شبکه‌ی خصوصی net1: هر منبع هنگام ساخته شدن به آن می‌پیوندد'],
};
// class names the app stylesheets also use: the landing copies get an lp- prefix so neither side leaks into the other
export const RENAME = ['acts', 'appr', 'big', 'brand', 'btn', 'btn-p', 'btn-s', 'chip', 'drop', 'ed', 'k', 'lead', 'led', 'm', 'n', 'nav', 'netbox', 'netlbl', 'nm', 'note', 'off', 'on', 'pl', 'pv', 'sk', 'sp', 'steps', 'stw', 'sub', 'tb', 'tick', 'v'];
const renameClassAttr = (html) => html.replace(/class="([^"]*)"/g, (_, c) => 'class="' + c.split(/\s+/).map((x) => (RENAME.includes(x) ? 'lp-' + x : x)).join(' ') + '"');
const out = {};
for (const [i, lang] of ['en', 'fa'].entries()) {
  const s = fs.readFileSync(path.join(dir, `landing-${lang}.html`), 'utf8');
  const svgs = s.match(/<svg\b[^>]*>[\s\S]*?<\/svg>/g);
  const pick = (cls) => svgs.filter((v) => v.startsWith('<svg class="' + cls));
  const tpl = (v) => {
    for (const [k, w] of Object.entries(WORDS)) v = v.replaceAll('>' + w[i] + '<', '>{{w.' + k + '}}<');
    for (const [k, w] of Object.entries(TITLES)) v = v.replaceAll('>' + w[i] + '<', '>{{w.title_' + k + '}}<');
    return renameClassAttr(v);
  };
  const [hw, sw] = pick('scene wide'), [ht, st] = pick('scene tall');
  const nw = svgs.find((v) => v.startsWith('<svg class="scene net wide')), nt = svgs.find((v) => v.startsWith('<svg class="scene net tall'));
  // ids must be unique per instance; they already are (t-phw, t-pht, t-psw, t-pst, n-pnw, n-pnt)
  out[lang] = { heroWide: tpl(hw), heroTall: tpl(ht), scrubWide: tpl(sw), scrubTall: tpl(st), netWide: tpl(nw), netTall: tpl(nt) };
  for (const [k, v] of Object.entries(out[lang])) {
    const left = [...v.matchAll(/>([^<>{}]*[^\x00-\x7f][^<>{}]*)</g)].map((m) => m[1]);
    if (lang === 'en' && left.length) console.log('non-ascii left in', lang, k, left);
    if (lang === 'fa') { const nonLatin = left.filter((x) => !/^[\x00-\x7f]+$/.test(x)); if (nonLatin.length) console.log('persian left in', k, nonLatin); }
  }
}
// the six orbs of the state legend and the small state icon
const s = fs.readFileSync(path.join(dir, 'landing-en.html'), 'utf8');
const svgs = s.match(/<svg\b[^>]*>[\s\S]*?<\/svg>/g);
const lines = ['// generated by scripts/gen-landing.mjs from design/landing. Do not edit.', 'export const SCENES = ' + JSON.stringify(out, null, 0) + ' as const;',
  'export const WORD_KEYS = ' + JSON.stringify(Object.fromEntries(Object.entries(WORDS).map(([k, w]) => [k, w[0]]))) + ';',
  'export const STATE_ICON = ' + JSON.stringify(renameClassAttr(svgs[6])) + ';', 'export const STATE_ORBS = ' + JSON.stringify(svgs.slice(9, 15).map(renameClassAttr)) + ';'];
fs.writeFileSync(path.join(root, 'src/landing/scenes.gen.ts'), lines.join('\n') + '\n');
// the catalog entries for the scene words
const cat = {}; for (const [lang, idx] of [['en', 0], ['fa', 1]]) { cat[lang] = {}; for (const [k, w] of Object.entries(WORDS)) cat[lang]['land.w.' + k] = w[idx]; for (const [k, w] of Object.entries(TITLES)) cat[lang]['land.w.title_' + k] = w[idx]; }
fs.writeFileSync(path.join(root, 'src/landing/scene-words.json'), JSON.stringify(cat, null, 1) + '\n');
console.log('scenes written', Object.keys(out.en));

// the stylesheet: the design's own CSS with fonts, tokens and colliding class names adapted
let css = s.match(/<style>([\s\S]*?)<\/style>/)[1];
css = css.replace(/html,body\{[^}]*\}\n?/, '');
const MONO_FA = '"JetBrains Mono","JetBrains Mono Fallback","Vazirmatn","Vazirmatn Fallback",ui-monospace,monospace';   // Persian inside a mono run still uses Vazirmatn
css = css.replaceAll("'Sora','Vazirmatn',system-ui,sans-serif", 'var(--f-sans)').replaceAll("'JetBrains Mono','Vazirmatn',ui-monospace,monospace", MONO_FA)
  .replaceAll("'JetBrains Mono','Vazirmatn',monospace", MONO_FA).replaceAll("'JetBrains Mono',monospace", 'var(--f-mono)').replaceAll("'Vazirmatn','Sora',system-ui,sans-serif", 'var(--f-fa)').replaceAll("'Vazirmatn',monospace", 'var(--f-fa)').replaceAll("'Vazirmatn','JetBrains Mono',monospace", 'var(--f-fa)');
css = css.replace(/^\.orb/gm, '.lp .orb').replace(/,\.orb/g, ',.lp .orb').replaceAll("'Vazirmatn',var(--f-mono)", 'var(--f-fa)');
const KF = ['spin', 'spinr', 'flow', 'ring', 'breathe', 'wob', 'draw', 'burst', 'jolt', 'shimmer'];
for (const k of KF) css = css.replace(new RegExp('@keyframes ' + k + '\\{', 'g'), '@keyframes lp-' + k + '{').replace(new RegExp('animation:' + k + '(?![\\w-])', 'g'), 'animation:lp-' + k);
for (const c of RENAME) css = css.replace(new RegExp('(?<![-]|\\d)\\.' + c.replace('-', '\\-') + '(?![\\w-])', 'g'), '.lp-' + c);
fs.writeFileSync(path.join(root, 'src/styles/landing.gen.css'), '/* generated by scripts/gen-landing.mjs from design/landing. Page-level additions live in landing.css. */\n' + css);
